#!/usr/bin/env node
// Writes the game cards from games.json straight into index.html, so the page
// is readable without JavaScript (link previews, crawlers, text-only tools).
// Run after editing games.json:   node build.js
// JavaScript (app.js) is only used to open and close the detail overlay.

const fs = require('fs');
const path = require('path');

const root = __dirname;
const data = JSON.parse(fs.readFileSync(path.join(root, 'games.json'), 'utf8'));
const indexPath = path.join(root, 'index.html');
let html = fs.readFileSync(indexPath, 'utf8');

const esc = (s) => String(s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const url = (s) => encodeURI(s).replace(/&/g, '&amp;');

function card(g) {
  const label = 'Open ' + g.title + (g.tag ? ' (' + g.tag + ')' : '');
  const pos = g.coverPosition ? ' style="object-position: ' + esc(g.coverPosition) + '"' : '';
  const results = (g.metrics || []).slice(0, 3).map((m) => m.label + ': ' + m.value).join('; ');
  const extra = [g.role ? 'Role: ' + g.role : '', results ? 'Key results: ' + results : '']
    .filter(Boolean).join(' ');
  return [
    '      <li>',
    '        <button type="button" class="card" data-slug="' + esc(g.slug) + '" aria-label="' + esc(label) + '">',
    '          <img src="' + url(g.base + g.cover) + '" alt="' + esc(g.coverAlt || g.title + ' cover') + '" loading="lazy"' + pos + '>',
    g.tag ? '          <span class="tag" aria-hidden="true">' + esc(g.tag) + '</span>' : null,
    '          <div class="info">',
    '            <h3>' + esc(g.title) + '</h3>',
    '            <p>' + esc(g.tagline) + '</p>',
    extra ? '            <span class="sr-only">' + esc(extra) + '</span>' : null,
    '          </div>',
    '        </button>',
    '      </li>'
  ].filter((l) => l !== null).join('\n');
}

const n = data.games.length;
const layout = n === 1 ? 'single' : (n % 3 === 1 ? 'one' : (n % 3 === 2 ? 'two' : 'even'));
const list = '<ul class="grid" id="grid" data-layout="' + layout + '">\n' +
  '      <!-- games:start (generated by build.js from games.json) -->\n' +
  data.games.map(card).join('\n') + '\n' +
  '      <!-- games:end -->\n' +
  '      </ul>';

const re = /<ul class="grid" id="grid"[^>]*>[\s\S]*?<\/ul>/;
if (!re.test(html)) throw new Error('Could not find <ul class="grid" id="grid"> in index.html');
const next = html.replace(re, () => list);
if (next !== html) fs.writeFileSync(indexPath, next);
console.log(n + ' game cards written to index.html (' + (next === html ? 'no change' : 'updated') + ')');
